Future<void> seedIfEmpty(Connection db) async {
  final count = await db.execute('SELECT count(*) FROM users');
  if ((firstValue(count) as int) > 0) return;

  for (final u in _users) {
    final salt = makeSalt();
    await db.execute(
      '''INSERT INTO users (id, name, email, phone, password_hash, password_salt,
           role, seller_status, shop_name, shop_location, shop_description, contact_info)
         VALUES (@id,@name,@email,@phone,@hash,@salt,@role,@sellerStatus,
           @shopName,@shopLocation,@shopDescription,@contactInfo)''',
      parameters: {
        'id': u['id'],
        'name': u['name'],
        'email': u['email'],
        'phone': u['phone'],
        'hash': hashPassword(u['password'] as String, salt),
        'salt': salt,
        'role': u['role'],
        'sellerStatus': u['sellerStatus'],
        'shopName': u['shopName'],
        'shopLocation': u['shopLocation'],
        'shopDescription': u['shopDescription'],
        'contactInfo': u['contactInfo'],
      },
    );
  }

  for (final p in _products) {
    await db.execute(
      '''INSERT INTO products (id, name, brand, category, description, price_tzs,
           ingredients, suitable_skin_types, targets_concerns, contains_flagged,
           is_comedogenic, usage_instructions, side_effects, warnings, stock,
           seller_id, shop_name, shop_location, approval)
         VALUES (@id,@name,@brand,@category,@description,@price,
           @ingredients,@skinTypes,@concerns,@flagged,@comedogenic,@usage,
           @sideEffects,@warnings,@stock,@sellerId,@shopName,@shopLocation,@approval)''',
      parameters: {
        'id': p['id'],
        'name': p['name'],
        'brand': p['brand'],
        'category': p['category'],
        'description': p['description'],
        'price': p['price'],
        'ingredients': p['ingredients'],
        'skinTypes': p['skinTypes'],
        'concerns': p['concerns'],
        'flagged': p['flagged'],
        'comedogenic': p['comedogenic'],
        'usage': p['usage'],
        'sideEffects': p['sideEffects'],
        'warnings': p['warnings'],
        'stock': p['stock'],
        'sellerId': p['sellerId'],
        'shopName': p['shopName'],
        'shopLocation': p['shopLocation'],
        'approval': p['approval'],
      },
    );
  }
}

